/**
 * Filter dokter jaga berdasarkan layanan klinik
 */
export function getDokterByLayanan(layanan: LayananRS | 'ALL'): DoctorDutyRecord[] {
  if (layanan === 'ALL') return DATA_DOKTER_JAGA_LENGKAP;
  return DATA_DOKTER_JAGA_LENGKAP.filter(d => d.layanan_utama === layanan);
}

/**
 * Filter dokter jaga IGD berdasarkan shift aktif
 */
export function getDokterJagaIGDByShift(shift: 'Pagi' | 'Siang' | 'Malam' | 'On-Call' | 'ALL'): DoctorDutyRecord[] {
  const igdDocs = DATA_DOKTER_JAGA_LENGKAP.filter(d => d.layanan_utama === 'IGD (Gawat Darurat)');
  if (shift === 'ALL') return igdDocs;
  if (shift === 'Pagi') return igdDocs.filter(d => d.shift.startsWith('Pagi'));
  if (shift === 'Siang') return igdDocs.filter(d => d.shift.startsWith('Siang'));
  if (shift === 'Malam') return igdDocs.filter(d => d.shift.startsWith('Malam'));
  if (shift === 'On-Call') return igdDocs.filter(d => d.shift.includes('On-Call'));
  return igdDocs;
}

/**
 * Cari dokter berdasarkan Poliklinik ID
 */
export function getDokterByPoliId(poliId: string): DoctorDutyRecord[] {
  return DATA_DOKTER_JAGA_LENGKAP.filter(d => d.poli_id === poliId);
}

/**
 * Mengambil ringkasan statistik dokter jaga aktif saat ini
 */
export function getSummaryDokterJaga() {
  const total = DATA_DOKTER_JAGA_LENGKAP.length;
  const aktifJaga = DATA_DOKTER_JAGA_LENGKAP.filter(d => d.status_kehadiran === 'Sedang Jaga / Praktik' || d.status_kehadiran === 'Tindakan OK' || d.status_kehadiran === 'Visite Bangsal').length;
  const onCall = DATA_DOKTER_JAGA_LENGKAP.filter(d => d.status_kehadiran === 'On-Call Cito').length;
  const sesiBerikutnya = DATA_DOKTER_JAGA_LENGKAP.filter(d => d.status_kehadiran === 'Sesi Berikutnya' || d.status_kehadiran === 'Tersedia').length;

  return {
    total,
    aktifJaga,
    onCall,
    sesiBerikutnya,
    layananIGD: DATA_DOKTER_JAGA_LENGKAP.filter(d => d.layanan_utama === 'IGD (Gawat Darurat)').length,
    layananPoli: DATA_DOKTER_JAGA_LENGKAP.filter(d => d.layanan_utama === 'Rawat Jalan (Poliklinik)').length,
    layananRanap: DATA_DOKTER_JAGA_LENGKAP.filter(d => d.layanan_utama === 'Rawat Inap (Bangsal & DPJP)').length,
    layananOK: DATA_DOKTER_JAGA_LENGKAP.filter(d => d.layanan_utama === 'Kamar Operasi (IBS / OK)').length,
    layananICU: DATA_DOKTER_JAGA_LENGKAP.filter(d => d.layanan_utama === 'ICU / Terapi Intensif').length,
    layananPenunjang: DATA_DOKTER_JAGA_LENGKAP.filter(d => d.layanan_utama === 'Laboratorium Patologi Klinik' || d.layanan_utama === 'Radiologi & Imejing' || d.layanan_utama === 'Rehabilitasi Medik' || d.layanan_utama === 'Gizi Klinik & Khusus').length
  };
}
